/**
 * `averri docs`: spec cards (SPEC-DECLARATIONS §7) written to one `SPEC.md` per directory that holds
 * declaration modules, plus the derived OpenAPI document. Both are projections of the graph.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { loadOrBuild, renderCardMarkdown, toOpenApi } from "@averri/compiler";
import type { Graph, Node, NodeId } from "@averri/ir";

const DECLARED = new Set(["Action", "Query", "Entity", "Policy", "Event", "Workflow", "Integration"]);

export interface DocsOptions {
  /** OpenAPI output path (repo-relative). Default `.averri/openapi.json`. */
  openapi?: string;
  /** Skip the SPEC.md files. */
  noSpec?: boolean;
}

export interface DocsResult {
  specFiles: string[];
  openapi: string;
  cards: number;
}

const byId = (a: Node, b: Node): number => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

export function renderSpecFile(graph: Graph, dir: string, nodes: Node[]): string {
  const title = dir === "." ? "project root" : dir;
  const parts = [`# Spec: ${title}`, "", "<!-- Generated by `averri docs` from the semantic graph. Do not edit. -->", ""];
  for (const n of nodes.sort(byId)) {
    const md = renderCardMarkdown(graph, n.id as NodeId);
    if (md) parts.push(md.trimEnd(), "");
  }
  return `${parts.join("\n").trimEnd()}\n`;
}

export function docsFromGraph(root: string, graph: Graph, options: DocsOptions = {}): DocsResult {
  const result: DocsResult = { specFiles: [], openapi: options.openapi ?? ".averri/openapi.json", cards: 0 };
  if (!options.noSpec) {
    const groups = new Map<string, Node[]>();
    for (const n of Object.values(graph.nodes) as Node[]) {
      if (!DECLARED.has(n.kind) || n.provenance.origin === "extracted" || !n.src) continue;
      const dir = path.posix.dirname(n.src.file);
      const list = groups.get(dir) ?? [];
      list.push(n);
      groups.set(dir, list);
    }
    for (const dir of [...groups.keys()].sort()) {
      const rel = dir === "." ? "SPEC.md" : `${dir}/SPEC.md`;
      const text = renderSpecFile(graph, dir, groups.get(dir) as Node[]);
      const abs = path.join(root, rel);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      if (!fs.existsSync(abs) || fs.readFileSync(abs, "utf8") !== text) fs.writeFileSync(abs, text);
      result.specFiles.push(rel);
      result.cards += groups.get(dir)?.length ?? 0;
    }
  }
  const out = path.join(root, result.openapi);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${JSON.stringify(toOpenApi(graph), null, 2)}\n`);
  return result;
}

export async function docs(root: string, options: DocsOptions = {}): Promise<DocsResult> {
  return docsFromGraph(root, await loadOrBuild(root), options);
}
