/**
 * Cache invalidation (SPEC-MCP §4) and the `.averri/` layout: fresh cache served without a build,
 * rebuild on content change / invalid cache / schema mismatch, generated tests excluded from the hash,
 * build lock, snapshot LRU with the last-green pin, determinism, and generated-test file management.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { extractProject } from "@averri/extract";
import { graphIdentityJson, serializeGraph, type Graph } from "@averri/ir";
import { build } from "../src/build.js";
import { acquireBuildLock, cachePath, pruneSnapshots, readCachedGraph, readSnapshot, readSnapshotByHash, writeLastGreen, writeSnapshot } from "../src/cache.js";
import { readConfig } from "../src/config.js";
import { computeContentHash } from "../src/inputs.js";
import { isFresh, loadOrBuildWithInfo } from "../src/load.js";
import { BUILD_TIMEOUT, copyFixture, type FixtureCopy } from "./helpers.js";

let fx: FixtureCopy;
let first: Graph;

beforeAll(async () => {
  fx = copyFixture("team-app");
  const r = await loadOrBuildWithInfo(fx.root, { git: false });
  expect(r.rebuilt).toBe(true);
  first = r.graph;
}, BUILD_TIMEOUT);

afterAll(() => fx?.cleanup());

describe("content hash", () => {
  it("the cheap staleness hash equals the extractor's content hash", () => {
    const { config } = readConfig(fx.root);
    const ex = extractProject(fx.root, {
      sourceRoots: config.sourceRoots,
      prismaSchema: config.prismaSchema,
      entryPoints: config.entryPoints,
      generatedDir: config.test.generatedDir,
      configFile: config.file,
    });
    expect(computeContentHash(fx.root, config)).toBe(ex.contentHash);
    expect(first.meta.contentHash).toBe(ex.contentHash);
  }, BUILD_TIMEOUT);

  it("generated tests are excluded from the hash (D-13)", () => {
    const { config } = readConfig(fx.root);
    const h = computeContentHash(fx.root, config);
    fx.write("tests/averri/Extra.gen.test.ts", "// @generated by averri 0.0.1 from Action:X hash:00 — do not edit\n");
    expect(computeContentHash(fx.root, config)).toBe(h);
    fs.rmSync(path.join(fx.root, "tests/averri"), { recursive: true, force: true });
  });
});

describe("loadOrBuild", () => {
  it("serves the cache when fresh (no rebuild)", async () => {
    const t = Date.now();
    const r = await loadOrBuildWithInfo(fx.root, { git: false });
    expect(r.rebuilt).toBe(false);
    expect(r.graph.meta.contentHash).toBe(first.meta.contentHash);
    expect(Date.now() - t).toBeLessThan(3000);
  });

  it("rebuilds after a source change and reports the new node", async () => {
    fx.edit("src/averri/events.ts", 'export const Audited = event("Audited", {', 'export const Pinged = event("Pinged", { payload: { at: "date" }, external: true });\n\nexport const Audited = event("Audited", {');
    const r = await loadOrBuildWithInfo(fx.root, { git: false });
    expect(r.rebuilt).toBe(true);
    expect(r.graph.meta.contentHash).not.toBe(first.meta.contentHash);
    expect(r.graph.nodes["Event:Pinged" as never]).toBeDefined();
    expect(isFresh(fx.root, readCachedGraph(fx.root))).toBe(true);
  }, BUILD_TIMEOUT);

  it("rebuilds when graph.json is corrupt or has another schemaVersion", async () => {
    fs.writeFileSync(cachePath(fx.root, "graph.json"), "{ not json");
    expect(readCachedGraph(fx.root)).toBeNull();
    let r = await loadOrBuildWithInfo(fx.root, { git: false });
    expect(r.rebuilt).toBe(true);
    const g = JSON.parse(fs.readFileSync(cachePath(fx.root, "graph.json"), "utf8")) as Graph;
    (g.meta as unknown as { schemaVersion: number }).schemaVersion = 999;
    fs.writeFileSync(cachePath(fx.root, "graph.json"), JSON.stringify(g));
    expect(readCachedGraph(fx.root)).toBeNull();
    r = await loadOrBuildWithInfo(fx.root, { git: false });
    expect(r.rebuilt).toBe(true);
  }, BUILD_TIMEOUT);

  it("rebuilds when the averri version differs", async () => {
    const r = await loadOrBuildWithInfo(fx.root, { git: false, averriVersion: "9.9.9" });
    expect(r.rebuilt).toBe(true);
    expect(r.graph.meta.averriVersion).toBe("9.9.9");
    const back = await loadOrBuildWithInfo(fx.root, { git: false });
    expect(back.rebuilt).toBe(true);
  }, BUILD_TIMEOUT);

  it("writes the cache layout: graph.json, snapshot, openapi.json, cards", () => {
    const g = readCachedGraph(fx.root) as Graph;
    expect(fs.existsSync(cachePath(fx.root, "snapshots", `${g.meta.contentHash}.json`))).toBe(true);
    expect(JSON.parse(fs.readFileSync(cachePath(fx.root, "openapi.json"), "utf8"))).toMatchObject({ openapi: "3.1.0" });
    expect(fs.existsSync(cachePath(fx.root, "cards", `${encodeURIComponent("Action:Team.inviteMember")}.md`))).toBe(true);
  });
});

describe("build lock", () => {
  it("serialises concurrent builders and breaks stale locks", async () => {
    const lock = await acquireBuildLock(fx.root);
    let second = false;
    const waiting = acquireBuildLock(fx.root, 5000, 10).then((l) => {
      second = true;
      return l;
    });
    await new Promise((r) => setTimeout(r, 100));
    expect(second).toBe(false);
    lock.release();
    (await waiting).release();
    expect(second).toBe(true);
    // a stale lock (older than 60 s) is broken
    const file = cachePath(fx.root, "build.lock");
    fs.writeFileSync(file, "999999 stale\n");
    const old = new Date(Date.now() - 120_000);
    fs.utimesSync(file, old, old);
    const l = await acquireBuildLock(fx.root, 1000, 10);
    l.release();
  });
});

describe("snapshots", () => {
  it("prunes to the 20 most recent but keeps the last-green snapshot", () => {
    const g = readCachedGraph(fx.root) as Graph;
    const pinnedGraph = { ...g, meta: { ...g.meta, contentHash: "pinned".padEnd(64, "0") } };
    const pinned = writeSnapshot(fx.root, pinnedGraph);
    writeLastGreen(fx.root, { meta: pinnedGraph.meta, tests: [], at: "2026-10-25T00:00:00.000Z", snapshot: pinned });
    const old = new Date(Date.now() - 3_600_000);
    fs.utimesSync(cachePath(fx.root, pinned), old, old);
    for (let i = 0; i < 25; i++) writeSnapshot(fx.root, { ...g, meta: { ...g.meta, contentHash: String(i).padStart(64, "a") } });
    pruneSnapshots(fx.root);
    const files = fs.readdirSync(cachePath(fx.root, "snapshots"));
    expect(files.length).toBe(21);
    expect(files).toContain(path.basename(pinned));
  });
});

describe("snapshots across Averri versions (D-41j)", () => {
  it("a snapshot written by another build is not served as a diff base and is replaced by the current build's", () => {
    const g = readCachedGraph(fx.root) as Graph;
    const hash = "v".padEnd(64, "1");
    const old = { ...g, meta: { ...g.meta, contentHash: hash, averriVersion: "0.0.0-old" } };
    const rel = writeSnapshot(fx.root, old);
    // gated read: same version only
    expect(readSnapshotByHash(fx.root, hash, "0.0.0-old")?.meta.averriVersion).toBe("0.0.0-old");
    expect(readSnapshotByHash(fx.root, hash, g.meta.averriVersion)).toBeNull();
    // ungated explicit reads (the pinned last-green) still return it
    expect(readSnapshot(fx.root, rel)?.meta.averriVersion).toBe("0.0.0-old");
    // the current build overwrites the stale file instead of keeping it forever
    writeSnapshot(fx.root, { ...g, meta: { ...g.meta, contentHash: hash } });
    expect(readSnapshotByHash(fx.root, hash, g.meta.averriVersion)?.meta.averriVersion).toBe(g.meta.averriVersion);
    fs.rmSync(cachePath(fx.root, rel), { force: true });
  });
});

describe("determinism and generated tests", () => {
  it("two builds of identical content are byte-identical except builtAt/root", () => {
    const a = build(fx.root, { writeCache: false, git: false, now: () => new Date("2026-01-01T00:00:00Z") }).graph;
    const b = build(fx.root, { writeCache: false, git: false, now: () => new Date("2026-02-02T00:00:00Z") }).graph;
    expect(graphIdentityJson(a)).toBe(graphIdentityJson(b));
    expect(serializeGraph(a)).not.toBe(serializeGraph(b));
  }, BUILD_TIMEOUT);

  it("A1002: an id that disappears while its run symbol reappears under a new id is a rename", () => {
    const previous = build(fx.root, { writeCache: false, git: false }).graph;
    fx.edit("src/averri/actions.ts", 'action("Team.rename", {', 'action("Team.renameTeam", {');
    const r = build(fx.root, { writeCache: false, git: false, previous }).graph;
    const d = r.diagnostics.find((x) => x.code === "A1002");
    expect(d).toMatchObject({ node: "Action:Team.renameTeam", severity: "warning" });
    expect(d?.message).toContain("Action:Team.rename disappeared");
    fx.edit("src/averri/actions.ts", 'action("Team.renameTeam", {', 'action("Team.rename", {');
  }, BUILD_TIMEOUT);

  it("since_last_green summarises the graph diff against the pinned snapshot", () => {
    const green = build(fx.root, { writeCache: false, git: false }).graph;
    fx.edit("src/averri/actions.ts", 'route: { method: "PATCH", path: "/teams/:teamId" }', 'route: { method: "PATCH", path: "/teams/:teamId/name" }');
    const r = build(fx.root, { writeCache: false, git: false, lastGreen: green }).graph;
    const a2101 = r.diagnostics.find((x) => x.code === "A2101" && x.node === "Action:Team.rename");
    expect(a2101?.since_last_green).toMatch(/~1 action/);
    const unrelated = r.diagnostics.find((x) => x.code === "A1003");
    expect(unrelated?.since_last_green).toBe("no changes");
    const noGreen = build(fx.root, { writeCache: false, git: false, lastGreen: null }).graph;
    expect(noGreen.diagnostics.every((x) => x.since_last_green === null)).toBe(true);
    fx.edit("src/averri/actions.ts", 'path: "/teams/:teamId/name" }', 'path: "/teams/:teamId" }');
  }, BUILD_TIMEOUT);

  it("writeTests writes generated files, clears A6001, and deletes files of vanished owners", () => {
    fx.write("tests/averri/Gone.gen.test.ts", "// @generated by averri 0.0.1 from Action:Gone.x hash:00 — do not edit\n");
    fx.write("tests/averri/handmade.test.ts", "// not generated\n");
    const r = build(fx.root, { writeCache: false, writeTests: true, git: false });
    expect(r.generated.written).toContain("tests/averri/Team.inviteMember.gen.test.ts");
    expect(r.generated.deleted).toEqual(["tests/averri/Gone.gen.test.ts"]);
    expect(fs.existsSync(path.join(fx.root, "tests/averri/handmade.test.ts"))).toBe(true);
    expect(r.graph.diagnostics.filter((d) => d.code === "A6001")).toEqual([]);
    expect(r.graph.meta.health.staleGeneratedTests).toBe(0);
    const again = build(fx.root, { writeCache: false, writeTests: true, git: false });
    expect(again.generated.written).toEqual([]);
    expect(again.generated.unchanged.length).toBe(r.generated.written.length);
  }, BUILD_TIMEOUT);
});
