import { validateGraph, type ContractNode, type Graph, type Node } from "@averri/ir";
import * as fc from "fast-check";
import { describe, expect, it } from "vitest";
import { generateTests, planTests, resolveOptions } from "../src/generate.js";
import { parseGeneratedHeader } from "../src/header.js";
import { relativeImport } from "../src/emit.js";
import { referenceGraph } from "./fixture-graph.js";

const ACTORS = ["anonymous", "member", "admin"];

function shuffled(graph: Graph, seed: number): Graph {
  const ids = Object.keys(graph.nodes);
  const order = fc.sample(fc.shuffledSubarray(ids, { minLength: ids.length, maxLength: ids.length }), { seed, numRuns: 1 })[0] as string[];
  const nodes: Record<string, Node> = {};
  for (const id of order) nodes[id] = graph.nodes[id as keyof typeof graph.nodes] as Node;
  const edges = [...graph.edges].reverse();
  return { ...graph, nodes: nodes as Graph["nodes"], edges };
}

describe("generateTests", () => {
  const graph = referenceGraph();
  const files = generateTests(graph, { actors: ACTORS });

  it("the fixture graph itself is a valid Graph", () => {
    expect(() => validateGraph(JSON.parse(JSON.stringify(graph)))).not.toThrow();
  });

  it("emits one file per owner with suites, sorted by path", () => {
    expect(files.map((f) => f.path)).toEqual([
      "tests/averri/Github.gen.test.ts",
      "tests/averri/Health.ping.gen.test.ts",
      "tests/averri/Invitation.gen.test.ts",
      "tests/averri/Legacy.gen.test.ts",
      "tests/averri/MemberInvited.gen.test.ts",
      "tests/averri/Stripe.gen.test.ts",
      "tests/averri/Team.archive.gen.test.ts",
      "tests/averri/Team.inviteMember.gen.test.ts",
      "tests/averri/Team.listMembers.gen.test.ts",
      "tests/averri/Team.rename.gen.test.ts",
      "tests/averri/Unresolved.gen.test.ts",
    ]);
    const invite = files.find((f) => f.owner === "Action:Team.inviteMember")!;
    expect(invite.tests).toEqual([
      "Test:gen/Team.inviteMember.auth-matrix",
      "Test:gen/Team.inviteMember.precondition",
      "Test:gen/Team.inviteMember.postcondition",
      "Test:gen/Team.inviteMember.event",
      "Test:gen/Team.inviteMember.pitfall.idempotency",
    ]);
    // Orphan event (no workflow) and Entities without invariants yield no file
    expect(files.some((f) => f.owner === "Event:Orphan")).toBe(false);
    expect(files.some((f) => f.owner === "Entity:Team")).toBe(false);
  });

  it("is deterministic: byte-identical across runs and node/edge order permutations", () => {
    const again = generateTests(graph, { actors: ACTORS });
    expect(again).toEqual(files);
    for (const seed of [1, 2, 3]) {
      const permuted = generateTests(shuffled(graph, seed), { actors: ACTORS });
      expect(permuted).toEqual(files);
    }
    expect(files.every((f) => !f.content.includes("\r"))).toBe(true);
  });

  it("headers carry version, owner and the sourceHash", () => {
    for (const f of files) {
      const h = parseGeneratedHeader(f.content);
      expect(h).toEqual({ averriVersion: "0.0.1", owner: f.owner, hash: f.hash });
      expect(f.content.split("\n")[0]).toBe(`// @generated by averri 0.0.1 from ${f.owner} hash:${f.hash} — do not edit`);
    }
    const custom = generateTests(graph, { actors: ACTORS, averriVersion: "9.9.9" });
    expect(parseGeneratedHeader(custom[0]!.content)?.averriVersion).toBe("9.9.9");
  });

  it("every it() title starts with the suite id and names the contract it asserts", () => {
    const invite = files.find((f) => f.owner === "Action:Team.inviteMember")!.content;
    expect(invite).toContain('it("[Test:gen/Team.inviteMember.precondition] [Contract:Team.inviteMember.requires.notAlreadyMember] violation is rejected"');
    expect(invite).toContain('it("[Test:gen/Team.inviteMember.postcondition] [Contract:Team.inviteMember.ensures.pendingForEmail] holds on every accepted result"');
    expect(invite).toContain('it("[Test:gen/Team.inviteMember.event] [Contract:Team.inviteMember.ensures.eventEmitted] Event:MemberInvited emitted exactly 1"');
    expect(invite).toContain("it(`[Test:gen/Team.inviteMember.auth-matrix] [Policy:Team.OwnerOrAdmin] ${fixture}: app decision matches the declared policy`");
    expect(invite).toContain('describe("[Test:gen/Team.inviteMember.pitfall.idempotency]"');
    // the guard gets no test but is mentioned as opaque
    expect(invite).not.toContain("emailDomainAllowed] violation");
    expect(invite).toContain("opaque guards (emailDomainAllowed)");
  });

  it("declared vs observe assertion columns differ as specified", () => {
    const declared = files.find((f) => f.owner === "Action:Team.inviteMember")!.content;
    const observe = files.find((f) => f.owner === "Action:Team.rename")!.content;
    expect(declared).toContain('expect(res.status, "violating input").toBe(412);');
    expect(declared).toContain('expect(res.status, "anonymous actor").toBe(401);');
    expect(declared).toContain('expect(errorBody(res).contract).toBe("Policy:Team.OwnerOrAdmin");');
    expect(declared).toContain('const count = emittedCount(res.trace, "Event:MemberInvited");');
    expect(declared).toContain('expect(errorBody(res)).not.toMatchObject({ error: "PostconditionFailed"');
    expect(observe).toContain('expect(is2xx(res.status), "violating input must not be accepted").toBe(false);');
    expect(observe).toContain('expect(phaseRecord(res.trace, "requires", "Contract:Team.rename.requires.seatsPositive")?.ok).toBe(false);');
    expect(observe).toContain("expect([401, 403, 404], `denied actor: got ${res.status}`).toContain(res.status);");
    expect(observe).toContain('expect2xx(res, "allowed actor");');
    expect(observe).not.toContain("toBe(412)");
  });

  it("derives violating inputs per clause and subject fixtures for self.* clauses", () => {
    const rename = files.find((f) => f.owner === "Action:Team.rename")!.content;
    expect(rename).toContain("const input_violate_Team_rename_seatsPositive = fc.record({ teamId:");
    expect(rename).toContain("seats: fc.integer({ min: 0, max: 0 })");
    expect(rename).toContain('plan: fc.stringMatching(/^[a-z0-9]{1,12}$/).filter((v) => v !== "free" && v !== "pro")');
    expect(rename).toContain("name: fc.stringMatching(/^[a-z0-9]{0,0}$/)");
    expect(rename).toContain('const v_status = draw(fc.constantFrom("active", "suspended").filter((v) => v !== "active"));');
    expect(rename).toContain("await seedSubject_Team_rename_violate_teamActive(h, env);");
  });

  it("imports declaration modules, config and the entry point relative to the generated dir", () => {
    const invite = files.find((f) => f.owner === "Action:Team.inviteMember")!.content;
    expect(invite).toContain('import config from "../../averri.config.js";');
    expect(invite).toContain('import * as entry from "../../src/app.js";');
    expect(invite).toContain('import * as m0_inviteMember from "../../src/members/inviteMember.js";');
    expect(invite).toContain("modules: [m0_inviteMember]");
    const event = files.find((f) => f.owner === "Event:MemberInvited")!.content;
    expect(event).toContain('import * as m0_inviteFlow from "../../src/members/inviteFlow.js";');
    expect(event).toContain('import * as m1_inviteMember from "../../src/members/inviteMember.js";');
    const nested = generateTests(graph, { actors: ACTORS, generatedDir: "test/generated/averri", configFile: "config/averri.config.ts", entryPoint: "src/server/index.ts" });
    expect(nested[0]!.path).toBe("test/generated/averri/Github.gen.test.ts");
    expect(nested[0]!.content).toContain('import config from "../../../config/averri.config.js";');
    expect(nested[0]!.content).toContain('import * as entry from "../../../src/server/index.js";');
  });

  it("todo cases: guard policies, custom schemes, unresolved webhooks, unready writers", () => {
    const archive = files.find((f) => f.owner === "Action:Team.archive")!.content;
    expect(archive).toContain('it.todo("[Test:gen/Team.archive.auth-matrix] [Policy:Team.Legacy] Policy:Team.Legacy is an opaque guard; the auth matrix is not derivable (A2106)");');
    const legacy = files.find((f) => f.owner === "Integration:Legacy")!.content;
    expect(legacy).toContain('{ [SIGNATURE_HEADER]: "averri-invalid-signature" }');
    expect(legacy).toContain("it.todo(\"[Test:gen/Legacy.pitfall.raw-body] scheme \\\"custom\\\" cannot produce a validly signed body\");");
    const unresolved = files.find((f) => f.owner === "Integration:Unresolved")!.content;
    expect(unresolved).toContain("it.todo(\"[Test:gen/Unresolved.pitfall.webhook-signature] webhook route is not resolved");
    const plan = planTests(graph, { actors: ACTORS });
    expect(plan.find((s) => s.id === "Test:gen/Team.archive.auth-matrix")?.todos).toHaveLength(1);
    expect(plan.find((s) => s.id === "Test:gen/Team.inviteMember.precondition")?.todos).toEqual([]);
  });

  it("webhook pitfalls sign per scheme and the raw-body test uses a non-canonical body", () => {
    const stripe = files.find((f) => f.owner === "Integration:Stripe")!.content;
    expect(stripe).toContain("return { [SIGNATURE_HEADER]: `t=${t},v1=${v1}` };");
    expect(stripe).toContain('const SECRET_ENV = "STRIPE_WEBHOOK_SECRET";');
    expect(stripe).toContain("const NON_CANONICAL_BODY = ");
    expect(stripe).toContain('const TABLES = ["invitation", "membership", "team", "user"];');
    const github = files.find((f) => f.owner === "Integration:Github")!.content;
    expect(github).toContain('return { [SIGNATURE_HEADER]: createHmac("sha256", key).update(body).digest("hex") };');
    expect(github).not.toContain("raw-body");
  });

  it("the invariant file embeds its writers' machinery and the consumer file asserts registration", () => {
    const inv = files.find((f) => f.owner === "Entity:Invitation")!.content;
    expect(inv).toContain('const WRITERS = ["Action:Team.inviteMember"] as const;');
    expect(inv).toContain("fc.array(fc.constantFrom(...WRITERS), { minLength: 1, maxLength: 5 })");
    expect(inv).toContain("async function invokeAllowed_Team_inviteMember(");
    const ev = files.find((f) => f.owner === "Event:MemberInvited")!.content;
    expect(ev).toContain('expect(await h.consumerRegistered("Event:MemberInvited", "Workflow:InviteFlow")');
  });

  it("`only` restricts output to the named owners or suites", () => {
    expect(generateTests(graph, { actors: ACTORS, only: ["Action:Team.rename"] }).map((f) => f.owner)).toEqual(["Action:Team.rename"]);
    expect(generateTests(graph, { actors: ACTORS, only: ["Test:gen/MemberInvited.consumer"] }).map((f) => f.owner)).toEqual(["Event:MemberInvited"]);
    expect(generateTests(graph, { actors: ACTORS, only: ["Test:gen/Nope.consumer"] })).toEqual([]);
  });

  it("resolveOptions fills defaults and pins anonymous first", () => {
    const o = resolveOptions(graph, { actors: ["admin", "anonymous", "member"], generatedDir: "./tests\\averri/" });
    expect(o).toMatchObject({ generatedDir: "tests/averri", configFile: "averri.config.ts", entryPoint: "src/app.ts", averriVersion: "0.0.1", actors: ["anonymous", "admin", "member"], numRuns: 10, only: null });
    expect(resolveOptions(graph).actors).toEqual(["anonymous"]);
  });

  it("relativeImport", () => {
    expect(relativeImport("tests/averri", "src/app.ts")).toBe("../../src/app.js");
    expect(relativeImport("tests/averri", "averri.config.ts")).toBe("../../averri.config.js");
    expect(relativeImport("tests", "tests/helper.ts")).toBe("./helper.js");
    expect(relativeImport("", "src/x.mts")).toBe("./src/x.mjs");
  });

  it("a non-derivable valid input turns dependent suites into todos instead of failing", () => {
    const g = referenceGraph();
    const ping = g.nodes["Action:Health.ping"];
    if (ping?.kind === "Action") {
      ping.input = { zod: null, fields: ["payload"] };
      (g.nodes["Contract:Health.ping.ensures.pong"] as ContractNode).expr = { op: "eq", lhs: { ref: "result.ok" }, rhs: { lit: true } };
      g.nodes["Field:Team.payload" as keyof typeof g.nodes] = {
        id: "Field:Team.payload",
        kind: "Field",
        name: "payload",
        summary: "",
        provenance: { origin: "extracted", extractor: "prisma", confidence: 1, evidence: [] },
        src: null,
        entity: "Entity:Team",
        type: { kind: "scalar", name: "Json", list: false },
        optional: false,
        isId: false,
        unique: false,
        hasDefault: false,
      };
    }
    const file = generateTests(g, { actors: ACTORS, only: ["Action:Health.ping"] })[0]!;
    expect(file.content).toContain("it.todo(\"[Test:gen/Health.ping.postcondition] [Contract:Health.ping.ensures.pong] holds on every accepted result: valid input: no arbitrary for json field payload\");");
  });
});
