import { EdgeSchema, TestNodeSchema, computeCounts, validateGraph, type ContractNode, type Graph } from "@averri/ir";
import { describe, expect, it } from "vitest";
import { derivationInputs, sourceHashOf, writersOf, consumersOf } from "../src/hash.js";
import { isGeneratedTestStale, parseGeneratedHeader } from "../src/header.js";
import { deriveTestNodes } from "../src/nodes.js";
import { generateTests } from "../src/generate.js";
import { renderHeader } from "../src/prelude.js";
import { referenceGraph } from "./fixture-graph.js";

const ACTORS = ["anonymous", "member", "admin"];

describe("sourceHash", () => {
  it("is stable, hex, and shared by every suite of an owner", () => {
    const g = referenceGraph();
    const h1 = sourceHashOf(g, "Action:Team.inviteMember");
    expect(h1).toMatch(/^[0-9a-f]{64}$/);
    expect(sourceHashOf(referenceGraph(), "Action:Team.inviteMember")).toBe(h1);
    const files = generateTests(g, { actors: ACTORS });
    expect(files.find((f) => f.owner === "Action:Team.inviteMember")?.hash).toBe(h1);
  });

  it("ignores volatile properties but changes with contracts, policies and schema facts", () => {
    const base = referenceGraph();
    const h = sourceHashOf(base, "Action:Team.inviteMember");

    const moved = referenceGraph();
    const a = moved.nodes["Action:Team.inviteMember"];
    if (a) {
      a.src = { file: "src/other.ts", range: [[1, 0], [2, 0]] };
      a.summary = "changed";
    }
    expect(sourceHashOf(moved, "Action:Team.inviteMember")).toBe(h);

    const contract = referenceGraph();
    (contract.nodes["Contract:Team.inviteMember.ensures.pendingForEmail"] as ContractNode).expr = { op: "eq", lhs: { ref: "result.status" }, rhs: { lit: "accepted" } };
    expect(sourceHashOf(contract, "Action:Team.inviteMember")).not.toBe(h);

    const policy = referenceGraph();
    (policy.nodes["Contract:Team.OwnerOrAdmin.allow"] as ContractNode).expr = { op: "db.exists", model: "membership", where: { userId: { ref: "actor.id" } } };
    expect(sourceHashOf(policy, "Action:Team.inviteMember")).not.toBe(h);

    const schema = referenceGraph();
    const f = schema.nodes["Field:Membership.role"];
    if (f?.kind === "Field") f.optional = true;
    expect(sourceHashOf(schema, "Action:Team.inviteMember")).not.toBe(h);

    // an unrelated change leaves the hash alone
    const unrelated = referenceGraph();
    const github = unrelated.nodes["Integration:Github"];
    if (github?.kind === "Integration") github.nonTransactional = false;
    expect(sourceHashOf(unrelated, "Action:Team.inviteMember")).toBe(h);
  });

  it("derivation inputs name the right nodes per owner kind", () => {
    const g = referenceGraph();
    expect(Object.keys(derivationInputs(g, "Event:MemberInvited"))).toEqual(["Event:MemberInvited", "Workflow:InviteFlow"]);
    expect(Object.keys(derivationInputs(g, "Integration:Stripe"))).toEqual(["Integration:Stripe", "webhook.exposure"]);
    expect(Object.keys(derivationInputs(g, "Entity:Invitation"))).toContain("Action:Team.inviteMember");
    expect(Object.keys(derivationInputs(g, "Action:Team.inviteMember"))).toEqual(
      expect.arrayContaining(["Action:Team.inviteMember", "Policy:Team.OwnerOrAdmin", "Contract:Team.OwnerOrAdmin.allow", "Entity:Membership", "Field:Membership.role", "Entity:Invitation"]),
    );
    expect(derivationInputs(g, "Entity:Nope")).toEqual({});
    expect(writersOf(g, "Entity:Invitation")).toEqual(["Action:Team.inviteMember"]);
    expect(consumersOf(g, "Event:MemberInvited")).toEqual(["Workflow:InviteFlow"]);
    expect(consumersOf(g, "Event:Orphan")).toEqual([]);
  });
});

describe("generated header", () => {
  it("round-trips and rejects malformed headers", () => {
    const line = renderHeader("0.0.1", "Action:Team.inviteMember", "abc123");
    expect(line).toBe("// @generated by averri 0.0.1 from Action:Team.inviteMember hash:abc123 — do not edit");
    expect(parseGeneratedHeader(`${line}\nrest`)).toEqual({ averriVersion: "0.0.1", owner: "Action:Team.inviteMember", hash: "abc123" });
    expect(parseGeneratedHeader(`${line}\r\nrest`)).not.toBeNull();
    expect(parseGeneratedHeader("// hand written")).toBeNull();
    expect(parseGeneratedHeader(`x\n${line}`)).toBeNull();
    expect(parseGeneratedHeader("// @generated by averri 0.0.1 from Nope:x hash:ab — do not edit")).toBeNull();
  });
  it("isGeneratedTestStale compares hashes and treats missing files as stale", () => {
    const node = { sourceHash: "abc123", covers: [] };
    expect(isGeneratedTestStale(node, null)).toBe(true);
    expect(isGeneratedTestStale(node, "// nothing")).toBe(true);
    expect(isGeneratedTestStale(node, renderHeader("0.0.1", "Action:X.y", "abc123"))).toBe(false);
    expect(isGeneratedTestStale(node, renderHeader("0.0.1", "Action:X.y", "other"))).toBe(true);
    expect(isGeneratedTestStale({ covers: [] }, renderHeader("0.0.1", "Action:X.y", "abc123"))).toBe(true);
  });
});

describe("deriveTestNodes", () => {
  it("yields schema-valid Test nodes and verifiedBy edges that fit the graph", () => {
    const g = referenceGraph();
    const { nodes, edges } = deriveTestNodes(g, { actors: ACTORS });
    expect(nodes.map((n) => n.id)).toContain("Test:gen/Team.inviteMember.auth-matrix");
    for (const n of nodes) {
      expect(() => TestNodeSchema.parse(n)).not.toThrow();
      expect(n.generated).toBe(true);
      expect(n.sourceHash).toMatch(/^[0-9a-f]{64}$/);
      expect(n.title).toBe(`[${n.id}]`);
      expect(n.file).toMatch(/^tests\/averri\/.*\.gen\.test\.ts$/);
    }
    for (const e of edges) expect(() => EdgeSchema.parse(e)).not.toThrow();
    const auth = nodes.find((n) => n.id === "Test:gen/Team.inviteMember.auth-matrix")!;
    expect(auth.covers).toEqual(["Action:Team.inviteMember", "Policy:Team.OwnerOrAdmin"]);
    expect(auth.provenance).toMatchObject({ origin: "declared" });
    expect(edges.filter((e) => e.to === auth.id).map((e) => e.from)).toEqual(["Action:Team.inviteMember", "Policy:Team.OwnerOrAdmin"]);
    // Entities may not be verifiedBy sources; the contract still is
    const inv = nodes.find((n) => n.id === "Test:gen/Invitation.invariant")!;
    expect(inv.covers).toEqual(["Contract:Invitation.invariant.pendingHasNoAcceptedAt", "Entity:Invitation"]);
    expect(edges.filter((e) => e.to === inv.id).map((e) => e.from)).toEqual(["Contract:Invitation.invariant.pendingHasNoAcceptedAt"]);

    const merged: Graph = { ...g, nodes: { ...g.nodes }, edges: [...g.edges, ...edges] };
    for (const n of nodes) merged.nodes[n.id] = n;
    merged.meta = { ...merged.meta, counts: computeCounts(merged.nodes) };
    expect(() => validateGraph(JSON.parse(JSON.stringify(merged)), { strict: true })).not.toThrow();
  });
});
